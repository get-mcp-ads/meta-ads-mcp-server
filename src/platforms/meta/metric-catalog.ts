// Helper to get metric by key
// Also searches by apiField as a fallback for robustness
export function getMetricByKey(key: string): MetricDefinition | undefined {
  // First try to find by key (primary lookup)
  const byKey = METRIC_CATALOG.find((m) => m.key === key);
  if (byKey) return byKey;

  // Fallback: try to find by apiField (in case apiField was used instead of key)
  return METRIC_CATALOG.find((m) => m.apiField === key);
}

// Helper to get metrics by category
export function getMetricsByCategory(category: MetricDefinition["category"]): MetricDefinition[] {
  return METRIC_CATALOG.filter((m) => m.category === category);
}

// Helper to get native metrics only
export function getNativeMetrics(): MetricDefinition[] {
  return METRIC_CATALOG.filter((m) => m.type === "native");
}

// Helper to get calculated metrics only
export function getCalculatedMetrics(): MetricDefinition[] {
  return METRIC_CATALOG.filter((m) => m.type === "calculated");
}

// Helper to check if a metric is compatible with a breakdown
export function isMetricCompatibleWithBreakdown(metricKey: string, breakdownKey: string): boolean {
  const metric = getMetricByKey(metricKey);
  if (!metric) return false;

  if (metric.incompatibleBreakdowns?.includes(breakdownKey)) {
    return false;
  }

  return metric.compatibleBreakdowns.includes(breakdownKey) || metric.compatibleBreakdowns.length === 0;
}
